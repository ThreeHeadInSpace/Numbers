export function calculateLifePath(input: unknown, today = new Date()) {
  const birthDate = validateBirthDate(input, today);
  const [year, month, day] = birthDate.split("-").map(Number);
  const parts = [reduceNumber(day), reduceNumber(month), reduceNumber(year)];
  const total = parts.reduce((a, b) => a + b, 0);
  const number = reduceNumber(total);
  return {
    number,
    isMaster: masterNumbers.includes(number),
    parts,
    total,
    explanation: `Сокращаем день, месяц и год отдельно, сохраняя 11, 22 и 33: ${day} → ${parts[0]}, ${month} → ${parts[1]}, ${year} → ${parts[2]}. Затем ${parts.join(" + ")} = ${total}${total !== number ? ` → ${number}` : ""}.`,
    ...interpretations[number],
  };
}

export function periodParameters(birthDate: string, start: string) {
  const lifePath = calculateLifePath(birthDate).number;
  const [, month, day] = birthDate.split("-").map(Number);
  const days = Array.from({ length: 7 }, (_, index) => {
    const date = new Date(`${start}T12:00:00Z`);
    date.setUTCDate(date.getUTCDate() + index);
    const personalYear = reduceNumber(
      reduceNumber(day) +
        reduceNumber(month) +
        reduceNumber(date.getUTCFullYear()),
    );
    const personalMonth = reduceNumber(personalYear + date.getUTCMonth() + 1);
    return {
      date: date.toISOString().slice(0, 10),
      personalYear,
      personalMonth,
      personalDay: reduceNumber(personalMonth + date.getUTCDate()),
    };
  });
  return { lifePath, start: days[0].date, end: days[6].date, days };
}
export type Parameters = ReturnType<typeof periodParameters>;
export type FreeResult = ReturnType<typeof calculateLifePath>;
