export const masterNumbers = [11, 22, 33];
export function reduceNumber(value: number): number {
  while (value > 9 && !masterNumbers.includes(value)) {
    value = [...String(value)].reduce((sum, digit) => sum + Number(digit), 0);
  }
  return value;
}

export function validateBirthDate(input: unknown, today = new Date()): string {
  if (typeof input !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(input))
    throw new Error("Введите дату рождения целиком.");
  const [year, month, day] = input.split("-").map(Number);
  const date = new Date(Date.UTC(year, month - 1, day));
  if (
    year < 1900 ||
    date.getUTCFullYear() !== year ||
    date.getUTCMonth() !== month - 1 ||
    date.getUTCDate() !== day ||
    input > today.toISOString().slice(0, 10)
  ) {
    throw new Error(
      "Укажите существующую дату с 1900 года, не позднее сегодняшнего дня.",
    );
  }
  return input;
}

